"""Evidence-aware equity networks and provider fund holdings."""

import yfinance as yf

from services.cache_manager import cache_manager
from services.data_fetcher import get_company_profile, normalize_ticker, now_iso
from services.relationship_network import build_relationship_network
from services.research_workflow import ensure_research


def get_company_supply_chain(ticker):
    symbol = normalize_ticker(ticker)
    profile = get_company_profile(symbol)
    result = {
        "ticker": symbol,
        "name": profile["name"],
        "sector": profile["sector"],
        "upstream_suppliers": [],
        "downstream_customers": [],
        "view_type": "supply_chain",
        "data_source": "unavailable",
        "source_url": profile["source_url"],
        "message": "Verified supplier and customer relationships require company filings. No named counterparties are inferred from sector or generated by AI. Use your notebook to record links with evidence from annual reports.",
    }
    if profile.get("instrument_type") in {"ETF", "MUTUALFUND"}:
        result.update(
            view_type="etf_holdings",
            view_label="Provider fund holdings",
            holdings=[],
            message="Fund holdings are unavailable. Consult the fund's latest official fact sheet.",
        )
        key = f"fund_holdings_v2:{symbol}"
        cached = cache_manager.get(key)
        if cached:
            return cached
        try:
            frame = yf.Ticker(symbol).funds_data.top_holdings
            holdings = []
            for index, row in frame.iterrows():
                weight = float(row["Holding Percent"])
                if 0 <= weight <= 1:
                    holdings.append(
                        {
                            "name": str(row.get("Name") or index),
                            "ticker": str(index),
                            "weight_pct": round(weight * 100, 2),
                        }
                    )
            if holdings:
                result.update(
                    holdings=holdings,
                    data_source="yahoo_finance",
                    fetched_at=now_iso(),
                    message="Provider holdings; report date not supplied. Weights may not cover the full portfolio. Verify against the AMC fact sheet.",
                )
                cache_manager.set(key, result, ttl=3600)
        except Exception:
            pass
    if result["view_type"] == "supply_chain":
        result.update(build_relationship_network(profile, ensure_research(profile)))
    return result
